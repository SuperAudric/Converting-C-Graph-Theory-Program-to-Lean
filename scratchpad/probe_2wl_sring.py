def check_group(mul, name):
    n = len(mul)
    assert all(len(r) == n for r in mul), name
    assert all(mul[0][x] == x and mul[x][0] == x for x in range(n)), f"{name}: identity"
    for x in range(n):
        assert sorted(mul[x]) == list(range(n)), f"{name}: not a latin square"
    for x in range(n):
        for y in range(n):
            for z in range(n):
                if mul[mul[x][y]][z] != mul[x][mul[y][z]]:
                    raise AssertionError(f"{name}: not associative")
    return mul


def g_cyclic(m):
    return [[(a + b) % m for b in range(m)] for a in range(m)]


def g_direct(A, B):
    na, nb = len(A), len(B)
    idx = lambda a, b: a * nb + b
    return [[idx(A[a1][a2], B[b1][b2]) for a2 in range(na) for b2 in range(nb)]
            for a1 in range(na) for b1 in range(nb)]


def g_semidirect_cyclic(m, k, order=2):
    """Z_m  x|  Z_order  with the action x -> x^k  (k^order == 1 mod m required)."""
    assert pow(k, order, m) == 1
    els = [(r, s) for s in range(order) for r in range(m)]
    ix = {e: i for i, e in enumerate(els)}
    def mult(e1, e2):
        (r1, s1), (r2, s2) = e1, e2
        return ((r1 + r2 * pow(k, s1, m)) % m, (s1 + s2) % order)
    return [[ix[mult(e1, e2)] for e2 in els] for e1 in els]


def g_dicyclic(m):
    """Dic_m of order 4m: <a,b | a^{2m}=1, b^2=a^m, b a b^-1 = a^-1>."""
    N = 2 * m
    els = [(r, s) for s in range(2) for r in range(N)]
    ix = {e: i for i, e in enumerate(els)}
    def mult(e1, e2):
        (r1, s1), (r2, s2) = e1, e2
        r = (r1 + (r2 if s1 == 0 else -r2)) % N
        s = s1 + s2
        if s >= 2:
            s -= 2
            r = (r + m) % N
        return (r, s)
    return [[ix[mult(e1, e2)] for e2 in els] for e1 in els]


def g_perm(gens, deg):
    """The permutation group generated by `gens` (tuples), as a multiplication table."""
    idp = tuple(range(deg))
    els = {idp}
    frontier = [idp]
    while frontier:
        p = frontier.pop()
        for g in gens:
            q = tuple(g[p[i]] for i in range(deg))
            if q not in els:
                els.add(q)
                frontier.append(q)
    els = sorted(els, key=lambda p: (p != idp, p))
    ix = {e: i for i, e in enumerate(els)}
    return [[ix[tuple(e2[e1[i]] for i in range(deg))] for e2 in els] for e1 in els]


