def sring(mul, inv, S):
    """Basic-set partition of the Schur ring generated by S (= the 2-WL closure of
    Cay(G,S), which is translation-invariant hence an S-ring)."""
    n = len(mul)
    part = [0 if x == 0 else (1 if x in S else 2) for x in range(n)]
    while True:
        k = len(set(part))
        rank = {c: i for i, c in enumerate(sorted(set(part)))}
        part = [rank[c] for c in part]
        counts = [[0] * (k * k) for _ in range(n)]
        for t in range(n):
            base = part[t] * k
            row = mul[t]
            for u in range(n):
                counts[row[u]][base + part[u]] += 1
        sig = [(part[g], part[inv[g]], tuple(counts[g])) for g in range(n)]
        newrank = {s: i for i, s in enumerate(sorted(set(sig)))}
        new = [newrank[s] for s in sig]
        if len(set(new)) == len(set(part)):
            return new
        part = new


def cayley_adj(mul, S):
    n = len(mul)
    adj = [[0] * n for _ in range(n)]
    for x in range(n):
        for s in S:
            y = mul[x][s]
            adj[x][y] = adj[y][x] = 1
    return n, adj


def twowl_vertex(n, adj, vcol, cap_rounds=40):
    col = [0] * (n * n)
    init = {}
    for u in range(n):
        for v in range(n):
            k = (0 if u == v else 1, adj[u][v], vcol[u], vcol[v])
            col[u * n + v] = init.setdefault(k, len(init))
    for _ in range(cap_rounds):
        rank, new = {}, [0] * (n * n)
        for u in range(n):
            un = u * n
            for v in range(n):
                s = sorted((col[un + w], col[w * n + v]) for w in range(n))
                key = (col[un + v], tuple(s))
                r = rank.get(key)
                if r is None:
                    r = rank[key] = len(rank)
                new[un + v] = r
        if len(rank) == len(set(col)):
            break
        col = new
    return [col[u * n + u] for u in range(n)]


def connected(mul, S):
    n = len(mul)
    seen = {0}
    fr = [0]
    while fr:
        x = fr.pop()
        for s in S:
            y = mul[x][s]
            if y not in seen:
                seen.add(y)
                fr.append(y)
    return len(seen) == n


